package httpx

import "testing"

// 导出的 CSV 不能让 Excel 把单元格当公式执行。
//
// CSV 本身是对的（encoding/csv 会转义逗号引号换行），坏在**打开它的程序**：
// Excel/WPS 把以 = + @ 开头的格子当公式。而这套系统的导出就是给财务
// 用 Excel 打开的，客户名、备注、地址都来自用户输入——
// 其中"自助下单"那条路还是对公网开放的。
//
// 实测（修之前）：订单目的地填 `=1+1`，导出的 CSV 里原样是 `=1+1`。
func TestExportCellsAreNotFormulas(t *testing.T) {
	for _, c := range []struct{ in, want, why string }{
		{"=1+1", "'=1+1", "等号开头是公式"},
		{"=HYPERLINK(\"http://x\",\"点我\")", "'=HYPERLINK(\"http://x\",\"点我\")", "常见的钓鱼写法"},
		{"+86 13800138000", "'+86 13800138000", "加号开头——电话号码就长这样，很容易真的出现"},
		{"@sum(A1:A9)", "'@sum(A1:A9)", "@ 是 Lotus 风格的公式前缀，Excel 也认"},
		{"\tfoo", "'\tfoo", "制表符开头会被当成公式的前导空白"},

		// 减号要单独判：负数金额不能被误伤
		{"-1200.50", "-1200.50", "负数金额必须原样留着，加了引号 Excel 那一列就求不了和"},
		{"-0.01", "-0.01", "同上"},
		{"-1e3", "-1e3", "科学计数法也是数字"},
		{"-cmd|'/c calc'!A1", "'-cmd|'/c calc'!A1", "减号开头但不是数字，照样是注入"},

		// 正常内容不能被动
		{"上海,某某\"公司", "上海,某某\"公司", "逗号引号由 csv 包转义，不该在这里动"},
		{"1200.50", "1200.50", "正数不动"},
		{"", "", "空串不动"},
		{"演示·甲承运", "演示·甲承运", "中文不动"},
	} {
		if got := sanitizeCell(c.in); got != c.want {
			t.Errorf("sanitizeCell(%q) = %q，期望 %q —— %s", c.in, got, c.want, c.why)
		}
	}
}
